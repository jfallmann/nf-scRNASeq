#### Load single cell data generated by the NF pipeline ####
paths <- split_SCE_paths(opt$sce)
print(sprintf("Collecting pseudobulk counts of %d library file(s) ...", length(paths)))

pb <- aggregate_SCE_pseudobulk(opt$sce, assay = "RNA")
countData <- pb$counts
metadata <- pb$metadata
colnames(countData) <- normalize_analysis_name(colnames(countData))
metadata$Sample <- normalize_analysis_name(metadata$Sample)
metadata$Condition <- normalize_analysis_name(metadata$Condition)

### set reference condition ###
ref.Condition <- normalize_analysis_name(opt$baseCond)
conditions <- sort(unique(as.character(metadata$Condition)))

skipped <- list()
comparison_objs <- list()

if (length(conditions) < 2) {
    skipped[["single_condition"]] <- data.frame(
        contrast = "single_condition",
        reason = paste0("Only one condition present (", paste(conditions, collapse = ", "), "), no contrast can be formed"),
        stringsAsFactors = FALSE
    )
} else if (!ref.Condition %in% conditions) {
    skipped[["missing_baseline"]] <- data.frame(
        contrast = "missing_baseline",
        reason = paste0("Reference condition '", ref.Condition, "' not found in the pseudobulk metadata (", paste(conditions, collapse = ", "), ")"),
        stringsAsFactors = FALSE
    )
}

if (length(skipped) == 0) {
    for (t in setdiff(conditions, ref.Condition)) {
        contrast_name <- paste(t, ref.Condition, sep = "-vs-")
        n.reps <- vapply(c(t, ref.Condition), function(cn) sum(as.character(metadata$Condition) == cn), integer(1))
        if (any(n.reps < 2)) {
            skipped[[contrast_name]] <- data.frame(
                contrast = contrast_name,
                reason = paste0("Fewer than 2 replicates for condition(s): ", paste(names(n.reps)[n.reps < 2], collapse = ", ")),
                stringsAsFactors = FALSE
            )
            print(paste("SKIPPING", contrast_name, "-", skipped[[contrast_name]]$reason))
            next
        }

        print(paste("ANALYSING ", contrast_name))
        ddslist <- run_deseq_contrast(contrast_name, metadata, countData)
        comparison_objs[[contrast_name]] <- ddslist

        deres <- ddslist[["res"]]

        write.table(deres, gzfile(paste0("DE_DESEQ2_", contrast_name, "_GENES_all.tsv.gz")), sep = "\t", row.names = FALSE, quote = FALSE)

        significant <- deres[!is.na(deres$p.adj) & deres$p.adj <= opt$pcut & abs(deres$log2FoldChange) >= opt$fcut, , drop = FALSE]
        write.table(significant, gzfile(paste0("DE_DESEQ2_", contrast_name, "_GENES_significant.tsv.gz")), sep = "\t", row.names = FALSE, quote = FALSE)

        pdf(
            file = paste0("DE_DESEQ2_", contrast_name, "_GENES_Volcano_p", opt$pcut, "_lfc", opt$fcut, ".pdf"),
            width = 15, height = 10
        )
        print(EnhancedVolcano(deres,
            lab = deres$Gene,
            x = "log2FoldChange",
            y = "p.adj",
            title = paste0(contrast_name, "_p", opt$pcut, "_lfc", opt$fcut, sep = ""),
            pCutoff = opt$pcut,
            FCcutoff = opt$fcut,
            pointSize = 2.0,
            labSize = 4.0,
            colAlpha = .2,
            xlab = bquote(~ Log[2] ~ "fold change"),
            ylab = bquote(~ Log[10] ~ "padj"),
            boxedLabels = TRUE,
            # parseLabels = TRUE,
            legendLabels = c(
                "Not sig.", "Log (base 2) FC", "p-value",
                "p-value & Log (base 2) FC"
            ),
            legendPosition = "bottom",
            legendLabSize = 10,
            legendIconSize = 8.0,
            drawConnectors = TRUE,
            widthConnectors = 0.25
        ) + coord_flip())
        dev.off()
    }
}

